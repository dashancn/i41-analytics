import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { join, resolve } from 'node:path';

const literalChineseNames = {
  '/ascii-text-drawer': 'ASCII 艺术文本生成器',
  '/email-normalizer': '邮箱规范化',
  '/json-to-xml': 'JSON 转 XML',
  '/markdown-to-html': 'Markdown 转 HTML',
  '/regex-memo': '正则表达式备忘录',
  '/regex-tester': '正则表达式测试器',
  '/safelink-decoder': 'Outlook 安全链接解码器',
  '/xml-to-json': 'XML 转 JSON',
};

function chineseTitles(localeSource) {
  const titles = new Map();
  let currentTool;
  for (const line of localeSource.split('\n')) {
    const tool = line.match(/^  ([a-z0-9-]+):\s*$/)?.[1];
    if (tool) currentTool = tool;
    const title = line.match(/^    title:\s*(?:'([^']*)'|"([^"]*)"|(.+))\s*$/);
    if (currentTool && title) titles.set(currentTool, (title[1] ?? title[2] ?? title[3]).trim());
  }
  return titles;
}

export function deriveToolsRouteNames(toolsRoot) {
  const titles = chineseTitles(readFileSync(join(toolsRoot, 'locales/zh.yml'), 'utf8'));
  const entries = [['/', '开发者工具']];
  for (const directory of readdirSync(join(toolsRoot, 'src/tools'), { withFileTypes: true })) {
    if (!directory.isDirectory()) continue;
    const indexPath = join(toolsRoot, 'src/tools', directory.name, 'index.ts');
    let source;
    try { source = readFileSync(indexPath, 'utf8'); } catch { continue; }
    if (!/\bcomponent\s*:/.test(source)) continue;
    const path = source.match(/\bpath\s*:\s*['"](\/[^'"]+)['"]/)?.[1];
    if (!path) continue;
    const translationKey = source.match(/\bname\s*:\s*translate\(['"]tools\.([a-z0-9-]+)\.title['"]\)/)?.[1];
    const name = translationKey ? titles.get(translationKey) : literalChineseNames[path];
    if (!name) throw new Error(`缺少中文名称: ${path}`);
    entries.push([path, name]);
  }
  return Object.fromEntries(entries.sort(([left], [right]) => left.localeCompare(right)));
}

export function renderRegistry(registry) {
  return `// Generated by scripts/import-tools-route-names.mjs; do not edit manually.\nexport const toolsRouteNames=${JSON.stringify(registry, null, 2)};\n`;
}

if (process.argv[1] && resolve(process.argv[1]) === resolve(new URL(import.meta.url).pathname)) {
  const toolsRoot = resolve(process.argv[2] || '../i41-audit/it-tools');
  const output = resolve(process.argv[3] || 'public/tool-route-names.js');
  writeFileSync(output, renderRegistry(deriveToolsRouteNames(toolsRoot)));
}
